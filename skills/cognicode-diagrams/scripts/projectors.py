#!/usr/bin/env python3
"""Manage LikeC4, Structurizr and Markmap LOCAL viewers for one external diagram workspace.

The script never mounts the Git worktree, invokes CogniCode, analyzes source, or
creates architecture diagrams. No container starts implicitly: `start` is explicit.
Podman is preferred, with Docker fallback. Standard library only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import HTTPRedirectHandler, ProxyHandler, Request, build_opener

# Import the same tested workspace resolver used by the entry skill.
from workspace import WorkspaceError, VALID_LENS, inspect as inspect_workspace

PROJECTORS = {
    "likec4": {"image": "likec4/likec4:latest", "container_port": 5173, "port": 5173},
    "structurizr": {"image": "structurizr/structurizr:2026.09.19", "container_port": 8080, "port": 8080},
    "markmap": {"image": "python:3.12-alpine", "container_port": 4173, "port": 4173},
}
LABEL_WORKSPACE = "dev.cognicode-diagrams.workspace"
LABEL_PROJECTOR = "dev.cognicode-diagrams.projector"
LABEL_LENS = "dev.cognicode-diagrams.lens"
LABEL_PORT = "dev.cognicode-diagrams.port"
LABEL_HMR = "dev.cognicode-diagrams.hmr-port"
# Minimal static server: only explicitly generated workspace paths, no directory listing.
MARKMAP_SERVER = r"""
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import unquote, urlsplit
import mimetypes, re

ROOT = Path('/data')
ALLOWED = re.compile(
    r'(?:navigation/atlas\.html|navigation/atlas\.md|'
    r'evidence/(?:claims|queries)\.json|'
    r'lenses/c4/renders/[a-z][a-z0-9-]*\.editorial\.html|'
    r'lenses/[a-z][a-z0-9-]*/(?:sources|renders)/[A-Za-z0-9_.() %\[\]-]+\.(?:dsl|mmd|c4|likec4|puml|d2|md|svg|png|webp))$'
)

class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        relative = unquote(urlsplit(self.path).path).lstrip('/') or 'navigation/atlas.html'
        if not ALLOWED.fullmatch(relative):
            self.send_error(404)
            return
        path = ROOT / relative
        if any(part.is_symlink() for part in (path, *path.parents) if part != ROOT.parent):
            self.send_error(403)
            return
        if not path.is_file() or not path.resolve().is_relative_to(ROOT):
            self.send_error(404)
            return
        data = path.read_bytes()
        editorial = relative.endswith('.editorial.html')
        if editorial and (not data.startswith(b'<!-- Generated by cognicode-diagrams editorial.py v1. -->')
                          or b'http-equiv="Content-Security-Policy"' not in data):
            self.send_error(403)
            return
        mime = mimetypes.guess_type(path.name)[0] or 'application/octet-stream'
        self.send_response(200)
        self.send_header('Content-Type', mime)
        self.send_header('Content-Length', str(len(data)))
        self.send_header('X-Content-Type-Options', 'nosniff')
        if editorial:
            # Opaque origin: even a tampered HTML file cannot access the local atlas.
            self.send_header('Content-Security-Policy',
                             "sandbox; default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'")
        self.send_header('Cache-Control', 'no-store')
        self.end_headers()
        self.wfile.write(data)

ThreadingHTTPServer(('0.0.0.0', 4173), Handler).serve_forever()
"""
NOT_FOUND = ("no such container", "no such object", "no container with name", "no such image or container")


class ProjectorError(ValueError):
    """Unsafe operation, invalid workspace or unexpected runtime response."""


def engine_binary(requested: str | None) -> str:
    if requested is not None:
        if requested not in {"podman", "docker"}:
            raise ProjectorError("solo se permite podman o docker")
        if not shutil.which(requested):
            raise ProjectorError(f"no se encuentra {requested} en PATH")
        return requested
    for executable in ("podman", "docker"):
        if shutil.which(executable):
            return executable
    raise ProjectorError("ni Podman ni Docker están disponibles")


def run_engine(engine: str, args: list[str], *, timeout: int = 90) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run([engine, *args], text=True, capture_output=True,
                              check=False, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise ProjectorError(f"fallo de {engine} {' '.join(args[:2])}: {exc}") from exc


def port_number(port: int) -> int:
    if not 1024 <= port <= 65535:
        raise ProjectorError("usar un puerto local libre entre 1024 y 65535")
    return port


def params(repo: Path, projector: str, *, lens: str = "c4", home: Path | None = None) -> dict:
    if projector not in PROJECTORS:
        raise ProjectorError(f"proyector no soportado: {projector}")
    if not VALID_LENS.fullmatch(lens):
        raise ProjectorError("lente no válida")
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise ProjectorError("workspace externo no preparado; ejecutar scripts/workspace.py init")
    workspace = Path(info["workspace"])
    source = workspace if projector == "markmap" else workspace / "lenses" / lens / "sources"
    if source.is_symlink() or not source.is_dir() or source.resolve() != source:
        raise ProjectorError("carpeta derivada insegura o inexistente")
    if source.is_relative_to(Path(info["repository"])):
        raise ProjectorError("prohibido montar directorios del repositorio Git")
    suffix = workspace.name.rsplit("--", 1)[-1]
    if not re.fullmatch(r"[a-f0-9]{12}", suffix):
        raise ProjectorError("identificador de workspace inesperado")
    lens_hash = hashlib.sha256(lens.encode("utf-8")).hexdigest()[:6]
    return {
        "workspace": str(workspace), "repository": info["repository"],
        "source": str(source), "projector": projector, "lens": lens,
        "name": f"cognicode-diagrams-{projector}-{lens[:22]}-{lens_hash}-{suffix}",
        "image": PROJECTORS[projector]["image"],
    }


def verify_sources(p: dict) -> None:
    src = Path(p["source"])
    if p["projector"] == "markmap":
        html = src / "navigation" / "atlas.html"
        if html.is_symlink() or not html.is_file():
            raise ProjectorError("primero renderizar navigation/atlas.html")
        if not html.read_text(encoding="utf-8").startswith("<!-- cognicode-diagrams markmap -->"):
            raise ProjectorError("HTML Markmap sin marca de procedencia valida")
    elif p["projector"] == "structurizr":
        model = src / "workspace.dsl"
        if model.is_symlink() or not model.is_file():
            raise ProjectorError("falta lenses/<lente>/sources/workspace.dsl (fuente creada por el agente)")
    elif not any(x.is_file() and not x.is_symlink() for x in src.rglob("*.c4")) and not any(
        x.is_file() and not x.is_symlink() for x in src.rglob("*.likec4")
    ):
        raise ProjectorError("falta fichero .c4 o .likec4 en lenses/<lente>/sources (lo crea el agente)")


def existing(engine: str, p: dict) -> dict | None:
    proc = run_engine(engine, ["inspect", p["name"]], timeout=15)
    if proc.returncode:
        if any(s in (proc.stderr or "").lower() for s in NOT_FOUND):
            return None
        raise ProjectorError(f"no se pudo inspeccionar contenedor: {proc.stderr.strip()[:400]}")
    try:
        data = json.loads(proc.stdout)
        meta = data[0] if isinstance(data, list) else data
        labels = meta["Config"]["Labels"] or {}
        if labels.get(LABEL_WORKSPACE) != p["workspace"] or labels.get(LABEL_PROJECTOR) != p["projector"] or labels.get(LABEL_LENS) != p["lens"]:
            raise ProjectorError("existe contenedor con el mismo nombre pero no pertenece a este workspace")
        if LABEL_PORT not in labels:
            raise ProjectorError("contenedor propio sin contrato de puerto")
        target = "/data" if p["projector"] in {"likec4", "markmap"} else "/usr/local/structurizr"
        mounts = meta.get("Mounts")
        if not isinstance(mounts, list) or len(mounts) != 1 or any(
            m.get("Source") != p["source"] or m.get("Destination") != target
            for m in mounts
        ):
            raise ProjectorError("montajes del contenedor no coinciden con el workspace externo")
        port_bindings = meta.get("HostConfig", {}).get("PortBindings") or {}
        if not isinstance(port_bindings, dict) or not port_bindings:
            raise ProjectorError("contenedor sin puertos locales comprobables")
        if any(binding.get("HostIp") not in {"127.0.0.1"}
               for bindings in port_bindings.values() for binding in (bindings or [])):
            raise ProjectorError("contenedor expuesto fuera de loopback")
        return {"running": bool(meta.get("State", {}).get("Running")), "labels": labels}
    except (IndexError, KeyError, TypeError, json.JSONDecodeError) as exc:
        raise ProjectorError("inspección del runtime sin metadatos fiables") from exc


class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise ProjectorError("se ha rechazado una redirección del visor local")


def http_ready(port: int) -> bool:
    opener = build_opener(ProxyHandler({}), NoRedirect())
    try:
        with opener.open(Request(f"http://127.0.0.1:{port}/", method="GET"), timeout=3) as response:
            return 200 <= response.status < 300
    except HTTPError as e:
        # Un error HTTP viene con el socket de respuesta abierto: cerrarlo
        # evita dejar conexiones colgando hasta que pase el recolector.
        e.close()
        return False
    except (URLError, TimeoutError, OSError):
        return False


def status(engine: str, p: dict, *, check_http: bool = False) -> dict:
    metadata = existing(engine, p)
    if metadata is None:
        state = "missing"
    elif not metadata["running"]:
        state = "stopped"
    else:
        state = "running"
        if check_http:
            port = port_number(int(metadata["labels"].get(LABEL_PORT, PROJECTORS[p["projector"]]["port"])))
            state = "ready" if http_ready(port) else "running_unverified"
    root = None if metadata is None else f"http://127.0.0.1:{metadata['labels'].get(LABEL_PORT)}/"
    url = root + "navigation/atlas.html" if root and p["projector"] == "markmap" else root
    return {**p, "engine": engine, "status": state, "url": url}


def start(engine: str, p: dict, *, port: int, hmr_port: int) -> dict:
    """Explicitly requested runtime mutation, bound to isolated HOME workspace."""
    verify_sources(p)
    port_number(port)
    port_number(hmr_port)
    if p["projector"] == "likec4" and hmr_port == port:
        raise ProjectorError("el puerto web y el puerto HMR deben ser diferentes")
    metadata = existing(engine, p)
    if metadata is not None:
        labels = metadata["labels"]
        if labels.get(LABEL_PORT) != str(port) or (p["projector"] == "likec4" and labels.get(LABEL_HMR) != str(hmr_port)):
            raise ProjectorError("contenedor existente utiliza otros puertos; detener y eliminarlo explícitamente")
        if metadata["running"]:
            return status(engine, p, check_http=True)
        proc = run_engine(engine, ["start", p["name"]], timeout=90)
    else:
        args = ["run", "-d", "--name", p["name"],
                "--label", f"{LABEL_WORKSPACE}={p['workspace']}",
                "--label", f"{LABEL_PROJECTOR}={p['projector']}",
                "--label", f"{LABEL_LENS}={p['lens']}",
                "--label", f"{LABEL_PORT}={port}",
                "-p", f"127.0.0.1:{port}:{PROJECTORS[p['projector']]['container_port']}",
                "-v", f"{p['source']}:{'/data' if p['projector'] in {'likec4', 'markmap'} else '/usr/local/structurizr'}:{'ro,z' if p['projector'] == 'markmap' else 'z'}"]
        if p["projector"] == "markmap":
            args.extend(["--read-only", "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
                         "--pids-limit", "64", p["image"], "python3", "-u", "-c", MARKMAP_SERVER])
        elif p["projector"] == "likec4":
            args.extend(["--label", f"{LABEL_HMR}={hmr_port}",
                         "-p", f"127.0.0.1:{hmr_port}:24678", p["image"],
                         "serve", "--listen", "0.0.0.0", "--port", "5173", "--hmr-port", "24678"])
        else:
            args.extend(["-e", "STRUCTURIZR_EDITABLE=false",
                         "-e", "STRUCTURIZR_AUTOSAVEINTERVAL=0",
                         "-e", "STRUCTURIZR_AUTOREFRESHINTERVAL=2000",
                         p["image"], "local"])
        proc = run_engine(engine, args, timeout=180)
    if proc.returncode:
        raise ProjectorError(f"no se pudo arrancar {p['projector']}: {proc.stderr.strip()[:400]}")
    return status(engine, p, check_http=True)


def stop_or_remove(engine: str, p: dict, *, remove: bool) -> dict:
    metadata = existing(engine, p)
    if metadata is None:
        return status(engine, p)
    if metadata["running"]:
        proc = run_engine(engine, ["stop", p["name"]], timeout=90)
        if proc.returncode:
            raise ProjectorError(f"falló stop: {proc.stderr.strip()[:400]}")
    if remove:
        proc = run_engine(engine, ["rm", p["name"]], timeout=90)
        if proc.returncode:
            raise ProjectorError(f"falló rm: {proc.stderr.strip()[:400]}")
    return status(engine, p)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("status", "start", "stop", "remove"))
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--projector", required=True, choices=tuple(PROJECTORS))
    parser.add_argument("--lens", default="c4", help="Lente (markmap sirve el atlas completo)")
    parser.add_argument("--engine", choices=("podman", "docker"), help="Por defecto prioriza Podman")
    parser.add_argument("--port", type=int)
    parser.add_argument("--hmr-port", type=int, default=24678)
    parser.add_argument("--check-http", action="store_true")
    args = parser.parse_args(argv)
    try:
        p = params(args.repo, args.projector, lens=args.lens)
        engine = engine_binary(args.engine)
        port = args.port or PROJECTORS[args.projector]["port"]
        if args.action == "status":
            result = status(engine, p, check_http=args.check_http)
        elif args.action == "start":
            result = start(engine, p, port=port, hmr_port=args.hmr_port)
        else:
            result = stop_or_remove(engine, p, remove=args.action == "remove")
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (ProjectorError, WorkspaceError, OSError) as exc:
        print(json.dumps({"status": "failed", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
