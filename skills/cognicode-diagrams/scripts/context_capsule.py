#!/usr/bin/env python3
"""M5 agent handoff from DERIVED CogniCode evidence; no checkout file reads."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile

import report_thinking as report
from workspace import inspect as inspect_workspace

GENERATOR = "cognicode-diagrams-capsule-v1"
MARKER = "<!-- Generated by cognicode-diagrams context_capsule.py v1. -->"
MAX_BYTES = 12000
MAX_EDGES = 4


class CapsuleError(ValueError):
    pass


def valid_goal(value):
    goal = report.text(value, "handoff goal", 240)
    if "\n" in goal or "\t" in goal:
        raise CapsuleError("handoff goal must be one line")
    return goal


def paths(root, symbol, goal, context=None):
    symbol = report.text(symbol, "symbol_id")
    goal = valid_goal(goal)
    if context is not None:
        report.slug(context, "context_id")
    token = json.dumps([symbol, context, goal], separators=(",", ":"), ensure_ascii=False)
    name = "capsule-" + hashlib.sha256(token.encode()).hexdigest()[:20]
    folder = report.safe(root / "handoffs", root)
    return (report.safe(folder / (name + ".capsule.json"), root),
            report.safe(folder / (name + ".capsule.md"), root))


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def model(root, symbol, goal, context=None):
    """Recompute on each call; source revision is never inferred from the cache."""
    goal = valid_goal(goal)
    symbol = report.text(symbol, "symbol_id")
    if context is not None:
        report.slug(context, "context_id")
    brief = report.project(root, "change-impact", symbol=symbol, context=context, goal=goal)
    change, evidence, language = brief["change"], brief["evidence"], brief["language"]
    incoming, outgoing = change["observed_incoming"], change["observed_outgoing"]
    sample = [("incoming", r) for r in incoming[:MAX_EDGES]]
    sample += [("outgoing", r) for r in outgoing[:MAX_EDGES]]
    relations = [
        {"direction": direction, "claim_id": r["claim_id"], "query_ids": r["query_ids"],
         "from_symbol": r["from_symbol"], "to_symbol": r["to_symbol"], "kind": r["kind"]}
        for direction, r in sample
    ]
    result = {
        "generator": GENERATOR, "schema_version": 1, "kind": "agent-handoff",
        "target": {"symbol_id": symbol, "context_id": context},
        "task": {"goal": goal, "authority": "user-intent-not-code-evidence"},
        "language": {k: language[k] for k in
                     ("label", "context_id", "term_id", "status", "definition",
                      "definition_authority")},
        "evidence": {
            "authority": "cognicode", "plane": "static", "basis": evidence["basis"],
            "coverage": evidence["coverage"],
            "claim_ids": sorted({x["claim_id"] for x in evidence["entities"]} |
                                {x["claim_id"] for x in relations}),
            "query_ids": sorted({q for x in relations for q in x["query_ids"]} |
                                {q for x in evidence["entities"] for q in x["query_ids"]}),
            "source_claim_count": len(evidence["claim_ids"]),
            "source_query_count": len(evidence["query_ids"]),
            # Derived artifact digest is NEVER a source-revision proof.
            "derivation_sha256": hashlib.sha256(canonical(brief).encode()).hexdigest(),
            "revision_freshness": "UNVERIFIED_WITH_RUNTIME",
        },
        "observed_relations": relations,
        "relation_scope": {
            "listed": len(relations),
            "observed_in_ledger": len(incoming) + len(outgoing),
            "omitted_from_capsule": len(incoming) + len(outgoing) - len(relations),
            "previously_truncated": evidence["related_truncated"],
            "global_coverage": False
        },
        "possible_impact": {
            "status": "HYPOTHESIS_NOT_VALIDATED",
            "candidate_symbols": sorted({r["from_symbol"] for r in incoming}),
            "impact_verified": False, "edit_authorized": False,
        },
        "unknowns": change["unknowns"],
        "next_questions": change["next_questions"],
        "receiver_contract": {
            "reader": "cognicode-cli-or-mcp-only",
            "forbidden_target_access": [
                "read_file", "grep", "git", "github_source", "ide_files",
                "shell_file_reads", "agent_file_reader", "file_search",
            ],
            "when_unavailable": "PAUSED_NO_FALLBACK",
            "required_before_action": [
                "discover_installed_cognicode_capabilities_for_language",
                "revalidate_symbol_and_source_revision_via_cognicode",
                "query_missing_contracts_with_structured_cognicode_capability",
                "never_edit_on_capsule_authority",
            ]
        },
        "status": "PARTIAL_HANDOFF",
        "certification": "derived-context-not-live-code-verification"
    }
    if len(canonical(result).encode("utf-8")) > MAX_BYTES:
        raise CapsuleError("capsule exceeds output budget; narrow the question")
    return result


def literal(value):
    if value is None:
        return "No disponible"
    return (str(value).replace("\\", "\\\\").replace("<", "&lt;").replace(">", "&gt;")
            .replace("[", "\\[").replace("]", "\\]").replace("*", "\\*")
            .replace("_", "\\_").replace(chr(96), "\\" + chr(96))
            .replace("|", "\\|").replace("\n", " "))


def markdown(data):
    e, language = data["evidence"], data["language"]
    scope = data["relation_scope"]
    lines = [
        MARKER, "# Traspaso de conocimiento", "",
        "**Cambio solicitado:** " + literal(data["task"]["goal"]),
        "**Concepto:** " + literal(language["label"]) + " (" + literal(language["status"]) + ")",
        "**Contexto DDD:** " + literal(data["target"]["context_id"]),
        "**Símbolo CogniCode:** " + literal(data["target"]["symbol_id"]), "",
        "## Qué sabemos (relaciones estáticas)", ""
    ]
    if data["observed_relations"]:
        for r in data["observed_relations"]:
            lines.append("- " + literal(r["from_symbol"]) + " → " + literal(r["to_symbol"]) +
                         " (" + literal(r["kind"]) + "; claim " + literal(r["claim_id"]) +
                         "; query " + literal(", ".join(r["query_ids"])) + ")")
    else:
        lines.append("No se encontraron relaciones en este ámbito. No demuestra que no existan.")
    lines += ["", "Mostradas " + str(scope["listed"]) + " de " + str(scope["observed_in_ledger"]) +
              " relaciones observadas; omitidas: " + str(scope["omitted_from_capsule"]) + ".",
              "", "## Qué es una hipótesis, NO un fallo", "",
              "Posibles consumidores para investigar: " +
              literal(", ".join(data["possible_impact"]["candidate_symbols"]) or "ninguno observado"),
              "", "## Qué desconocemos", ""]
    lines += ["- " + literal(x) for x in data["unknowns"]]
    lines += ["", "## Preguntas siguientes (solo CogniCode)", ""]
    lines += ["- " + literal(q["question"]) for q in data["next_questions"]]
    lines += ["", "## Contrato del agente receptor", "",
              "1. Descubrir el CogniCode instalado y sus capacidades reales para el lenguaje.",
              "2. Revalidar símbolo, evidencias y revisión exclusivamente mediante CogniCode.",
              "3. Consultar solo contratos o relaciones todavía necesarios usando CogniCode.",
              "4. Si no hay CogniCode: **PAUSED**, nunca lectura directa ni fallback.",
              "", "No autoriza editar ni verifica impacto runtime.",
              "Revisión declarada: " + literal(e["basis"]["identity"]) +
              " (" + literal(e["basis"]["status"]) + ").",
              "Vigencia del código: NO comprobada.", ""]
    return "\n".join(lines)


def owned(path, root, json_file):
    report.safe(path, root)
    if not path.exists():
        return
    if not path.is_file() or path.stat().st_size > MAX_BYTES * 2:
        raise CapsuleError("unsafe existing capsule output")
    try:
        old = path.read_text(encoding="utf-8")
        ok = (isinstance(json.loads(old), dict) and
              json.loads(old).get("generator") == GENERATOR) if json_file else old.startswith(MARKER)
    except (UnicodeError, ValueError):
        ok = False
    if not ok:
        raise CapsuleError("unowned capsule output refused")


def atomic(path, value, root, json_file):
    owned(path, root, json_file)
    if path.is_file() and path.read_text(encoding="utf-8") == value:
        return
    fd, tmp = tempfile.mkstemp(prefix=".capsule-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as target:
            target.write(value)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def resume(root, symbol, goal, context=None):
    """Ledger reconciliation, NOT runtime/source freshness certification."""
    expected = model(root, symbol, goal, context)
    jp, md = paths(root, symbol, goal, context)
    for p in (jp, md):
        report.safe(p, root)
        if not p.is_file() or p.stat().st_size > MAX_BYTES * 2:
            return {"status": "MISSING_OR_UNSAFE_CAPSULE", "runtime_verified": False}
    try:
        existing = json.loads(jp.read_text(encoding="utf-8"))
        rendered = md.read_text(encoding="utf-8")
    except (UnicodeError, ValueError, OSError):
        return {"status": "INVALID_CAPSULE", "runtime_verified": False}
    if existing != expected or rendered != markdown(expected):
        return {"status": "STALE_DERIVED_EVIDENCE", "runtime_verified": False,
                "next": "query-cognicode"}
    return {"status": "LEDGER_MATCHES_RUNTIME_UNVERIFIED", "runtime_verified": False,
            "basis": expected["evidence"]["basis"],
            "next": "revalidate-by-cognicode", "code_access": "cognicode-only"}


def build(repo, symbol, goal, *, context=None, home=None, check=False, receiving=False):
    workspace = inspect_workspace(repo, home=home)
    if workspace["status"] != "ready":
        raise CapsuleError("unsafe or absent workspace; never read target checkout")
    root = Path(workspace["workspace"])
    if receiving:
        return resume(root, symbol, goal, context)
    data = model(root, symbol, goal, context)
    jp, md = paths(root, symbol, goal, context)
    if check:
        return {"status": "EVIDENCE_READY", "kind": "agent-handoff",
                "basis": data["evidence"]["basis"],
                "revision_freshness": "UNVERIFIED_WITH_RUNTIME",
                "estimated_json_bytes": len(canonical(data).encode("utf-8"))}
    folder = report.safe(jp.parent, root)
    if folder.exists() and not folder.is_dir():
        raise CapsuleError("unsafe capsule directory")
    folder.mkdir(exist_ok=True)
    owned(jp, root, True)
    owned(md, root, False)
    atomic(jp, json.dumps(data, sort_keys=True, ensure_ascii=False, indent=2) + "\n", root, True)
    atomic(md, markdown(data), root, False)
    return {"status": "PARTIAL_HANDOFF", "json": str(jp), "markdown": str(md),
            "revision_freshness": "UNVERIFIED_WITH_RUNTIME",
            "next": "revalidate-by-cognicode"}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo", required=True, type=Path)
    p.add_argument("--symbol", required=True)
    p.add_argument("--goal", required=True)
    p.add_argument("--context")
    group = p.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true")
    group.add_argument("--receive", action="store_true")
    args = p.parse_args(argv)
    try:
        out = build(args.repo, args.symbol, args.goal, context=args.context,
                    check=args.check, receiving=args.receive)
        print(json.dumps(out, ensure_ascii=False, indent=2))
        return 2 if out["status"] in {"MISSING_OR_UNSAFE_CAPSULE",
                                      "INVALID_CAPSULE", "STALE_DERIVED_EVIDENCE"} else 0
    except (CapsuleError, report.ReportError, ValueError, OSError) as exc:
        print(json.dumps({"status": "BLOCKED", "error": str(exc)}, ensure_ascii=False),
              file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
