#!/usr/bin/env python3
"""Optional editorial C4 projection of an EXISTING CogniCode evidence view.

Reads ONLY derived workspace ledgers and a linked view report. Never reads the
checkout, guesses architecture from Mermaid, or invokes CogniCode/projectors.
The output is presentation, not independent certification of source code.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from html import escape
import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import quote
import tempfile

from evidence_contract import corroborated, index_claims, index_queries, provenance_of
from workspace import inspect as inspect_workspace

MARKER = "<!-- Generated by cognicode-diagrams editorial.py v1. -->"
VIEW_ID = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*\Z")
LIMIT = 2 * 1024 * 1024
WIDTH = 940
NODE_X, NODE_W, NODE_H = 56, 360, 80
DEFAULT_COLORS = {
    "paper": "#f8f7f3", "surface": "#ffffff", "ink": "#202b39",
    "stroke": "#293241", "muted": "#516173", "connector": "#64748b",
}
HEX_COLOR = re.compile(r"#[0-9a-fA-F]{6}\Z")


class EditorialError(ValueError):
    """Unsafe, unverifiable or too complex for an editorial projection."""


def safe(path: Path, workspace: Path) -> Path:
    """Reject symlinks and external files even for paths reached via manifests."""
    if not path.is_relative_to(workspace):
        raise EditorialError("asset outside the derived workspace")
    for p in (path, *path.parents):
        if p == workspace.parent:
            break
        if p.is_symlink():
            raise EditorialError("symlink in derived workspace")
    return path


def load(path: Path, workspace: Path):
    safe(path, workspace)
    if not path.is_file() or path.stat().st_size > LIMIT:
        raise EditorialError("missing or oversized derived input: " + str(path))
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeError) as exc:
        raise EditorialError("invalid derived JSON: " + str(path)) from exc


def records(value, key: str) -> list:
    if isinstance(value, dict):
        value = value.get(key)
    if not isinstance(value, list):
        raise EditorialError(key + " must be an array")
    return value


def plain(value, field: str) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > 400:
        raise EditorialError("invalid " + field)
    return value


def title_lines(value: str) -> list[str]:
    """Wrap, never silently erase a long symbol identity."""
    parts = [value[i:i + 47] for i in range(0, len(value), 47)]
    if len(parts) > 2:
        raise EditorialError("symbol label too long for editorial view; make a narrower view")
    return parts


def profile_colors(home: Path, profile: str) -> dict[str, str]:
    """Load optional user-owned presentation tokens; never touch a checkout."""
    if not VIEW_ID.fullmatch(profile):
        raise EditorialError("invalid profile name")
    if profile == "default":
        return DEFAULT_COLORS.copy()
    path = home / ".cognicode-diagrams" / "profiles" / (profile + ".json")
    if any(p.is_symlink() for p in (path, *path.parents) if p != home.parent):
        raise EditorialError("symlink in profile path")
    if not path.is_file() or path.stat().st_size > 2048:
        raise EditorialError("profile missing or oversized: " + profile)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeError) as exc:
        raise EditorialError("invalid profile JSON") from exc
    if (not isinstance(data, dict) or set(data) != set(DEFAULT_COLORS)
            or any(not isinstance(c, str) or not HEX_COLOR.fullmatch(c) for c in data.values())):
        raise EditorialError("profile must provide six hexadecimal color tokens")
    def luminance(code: str) -> float:
        values = [int(code[i:i+2], 16) / 255 for i in (1, 3, 5)]
        channels = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in values]
        return .2126 * channels[0] + .7152 * channels[1] + .0722 * channels[2]
    def contrast(a: str, b: str) -> float:
        x, y = sorted((luminance(a), luminance(b)))
        return (y + .05) / (x + .05)
    if min(contrast(data["paper"], data["ink"]),
           contrast(data["surface"], data["ink"]),
           contrast(data["paper"], data["muted"]),
           contrast(data["surface"], data["muted"])) < 4.5:
        raise EditorialError("profile fails 4.5:1 text contrast")
    return data


def model(workspace: Path, view_id: str) -> tuple[str, list, list, str]:
    report = load(workspace / "lenses" / "c4" / "reports" / (view_id + ".atlas.json"), workspace)
    if not isinstance(report, dict) or report.get("schema_version") != 1 or report.get("plane", "implementation") != "implementation":
        raise EditorialError("requires a C4 implementation view report")
    label = plain(report.get("label"), "view label")
    if len(label) > 70:
        raise EditorialError("view label too long for an accessible editorial header")
    ids = report.get("claim_ids")
    assets = report.get("assets")
    if (not isinstance(ids, list) or not ids or len(ids) > 40 or len(set(map(str, ids))) != len(ids)
            or not all(isinstance(x, str) and x for x in ids)):
        raise EditorialError("view needs distinct claim_ids")
    if not isinstance(assets, list) or not assets:
        raise EditorialError("view requires existing derived assets")
    managed = {f"lenses/c4/renders/{view_id}.editorial.svg",
               f"lenses/c4/renders/{view_id}.editorial.html"}
    technical_source_seen = False
    for asset in assets:
        if not isinstance(asset, str) or not (
            asset.startswith("lenses/c4/sources/") or asset.startswith("lenses/c4/renders/")
        ) or Path(asset).is_absolute() or ".." in Path(asset).parts:
            raise EditorialError("invalid view asset")
        target = safe(workspace / asset, workspace)
        if not target.is_file():
            # Generated editorial outputs can be repaired after deletion. Other
            # missing assets invalidate the source report: never invent a source.
            if asset in managed and not target.exists():
                continue
            raise EditorialError("missing view asset: " + asset)
        if asset not in managed:
            technical_source_seen = True
    if not technical_source_seen:
        raise EditorialError("view has no existing derived technical source")

    queries = records(load(workspace / "evidence" / "queries.json", workspace), "queries")
    # La forma la decide el contrato: las grafias antiguas se leen por
    # la misma autoridad que las comprueba, no por una copia local que
    # envejece mal.
    try:
        query_by_id = index_queries(queries)
    except ValueError as exc:
        raise EditorialError(str(exc)) from exc
    claims = records(load(workspace / "evidence" / "claims.json", workspace), "claims")
    try:
        by_id = index_claims(claims)
    except ValueError as exc:
        raise EditorialError(str(exc)) from exc

    nodes, edges, symbols = [], [], set()
    status = "SCOPED EVIDENCE"
    for cid in ids:
        if cid not in by_id:
            raise EditorialError("unknown claim: " + cid)
        claim = by_id[cid]
        query_ids = claim.get("query_ids")
        if (provenance_of(claim) not in {"OBSERVED_CODE", "observed"}
                or claim.get("category") == "intent" or claim.get("plane", "static") != "static"
                or not isinstance(query_ids, list) or not query_ids
                or not all(isinstance(q, str) and q in query_by_id for q in query_ids)):
            raise EditorialError("unsubstantiated/static-incompatible claim: " + cid)
        coverage = claim.get("coverage", "unknown")
        if coverage not in {"complete", "partial", "unknown"}:
            raise EditorialError("invalid coverage: " + cid)
        if coverage != "complete":
            status = "PARTIAL / UNKNOWN COVERAGE"
        # Query ID existence alone is NOT structural evidence. The actual
        # CogniCode query records must corroborate symbol/edge identity.
        selected_queries = [query_by_id[q] for q in query_ids]
        relevant_queries = [q for q in selected_queries
                            if q.get("mode") in {"structured", "symbol_context"}
                            and q.get("status") in {"ok", "partial"}
                            and q.get("observation_plane", "static") == "static"]
        kind = claim.get("kind", "entity")
        if kind == "entity":
            symbol = plain(claim.get("symbol_id"), "symbol_id")
            if not corroborated(claim, query_by_id):
                raise EditorialError("entity symbol not corroborated by CogniCode query: " + cid)
            if not isinstance(claim.get("category", "symbol"), str):
                raise EditorialError("invalid claim category: " + cid)
            if symbol in symbols:
                raise EditorialError("duplicate symbol in selected view: " + symbol)
            symbols.add(symbol)
            nodes.append({"id": cid, "symbol": symbol, "category": claim.get("category", "symbol"),
                          "queries": query_ids, "coverage": coverage})
        elif kind == "relation":
            if claim.get("relation_source") != "graph_edge":
                raise EditorialError("reference_link is not an architectural edge: " + cid)
            src = plain(claim.get("from_symbol"), "from_symbol")
            dst = plain(claim.get("to_symbol"), "to_symbol")
            relation_id = plain(claim.get("relation_id"), "relation_id")
            if not corroborated(claim, query_by_id):
                raise EditorialError("edge not corroborated by CogniCode query: " + cid)
            if src == dst:
                raise EditorialError("self-loop requires another representation: " + cid)
            attrs = claim.get("attributes", {})
            if not isinstance(attrs, dict):
                raise EditorialError("invalid relation attributes")
            relation = attrs.get("kind", "relation")
            edges.append({"id": cid, "src": src, "dst": dst,
                          "kind": plain(relation, "relation kind"), "queries": query_ids,
                          "coverage": coverage})
        else:
            raise EditorialError("unsupported claim kind: " + cid)

    if not 2 <= len(nodes) <= 9 or len(edges) > 12:
        raise EditorialError("editorial budget: 2–9 nodes and at most 12 edges; split the view")
    if any(e["src"] not in symbols or e["dst"] not in symbols for e in edges):
        raise EditorialError("edge endpoint lacks selected entity evidence")
    incident = defaultdict(list)
    for i, edge in enumerate(edges):
        incident[edge["src"]].append(i)
        incident[edge["dst"]].append(i)
    if any(len(v) > 5 for v in incident.values()):
        raise EditorialError("more than 5 ports on one node; split the view")
    return label, sorted(nodes, key=lambda n: n["symbol"]), edges, status



def contextual_nodes(workspace: Path, nodes: list, context: str | None, view_id: str) -> tuple[dict, dict]:
    """Names are curated/proposed vocabulary; links require current owned pages.

    The C4 model already established these symbol identities from structured
    CogniCode queries. Neither the vocabulary nor a local page adds code facts.
    """
    import report_thinking as reports
    from moldable_views import current_page

    try:
        if context is not None:
            reports.slug(context, "context_id")
        dictionary = reports.vocab(workspace)
        terms, links = {}, {}
        render_dir = workspace / "lenses" / "c4" / "renders"
        for n in nodes:
            symbol = n["symbol"]
            candidates = sorted(
                (t for t in dictionary.values()
                 if symbol in t["symbol_ids"]
                 and (context is None or t["context_id"] == context)
                 and t["status"] in {"accepted", "candidate"}),
                key=lambda t: (t["context_id"], t["term_id"]))
            if len(candidates) == 1:
                term = candidates[0]
                display = term["label"] + (" (propuesto)" if term["status"] == "candidate" else "")
                # Never truncate a term: show its technical ID if it does not fit.
                if len(display) <= 94:
                    terms[symbol] = {"label": display, "context_id": term["context_id"],
                                     "term_id": term["term_id"], "status": term["status"]}
            page = current_page(workspace, symbol, context)
            if page is not None:
                path = os.path.relpath(page, render_dir).replace(os.sep, "/")
                # Pure, local, percent-encoded URL; no url schemes or fragments.
                if not path.startswith("../../../navigation/moldable/"):
                    raise EditorialError("unexpected contextual navigation destination")
                links[symbol] = quote(path, safe="/.-_~")
        return terms, links
    except reports.ReportError as exc:
        raise EditorialError("invalid derived domain vocabulary: " + str(exc)) from exc


def draw(label: str, nodes: list, edges: list, status: str,
         colors: dict[str, str] | None = None, *,
         pattern: str = "topology", focus: str | None = None,
         terms: dict | None = None, links: dict | None = None) -> tuple[str, str]:
    esc = lambda v: escape(str(v), quote=True)
    colors = colors or DEFAULT_COLORS
    terms = terms or {}
    links = links or {}
    if pattern not in {"topology", "dependencies", "traceability"}:
        raise EditorialError("unsupported semantic editorial pattern")
    if focus is not None and focus not in {n["symbol"] for n in nodes}:
        raise EditorialError("focus is not a selected CogniCode symbol")
    degrees = {n["symbol"]: [0, 0] for n in nodes}
    for edge in edges:
        degrees[edge["src"]][1] += 1
        degrees[edge["dst"]][0] += 1
    positions = {n["symbol"]: 138 + i * 112 for i, n in enumerate(nodes)}
    height = 190 + 112 * len(nodes)
    paths, boxes = [], []
    incident = defaultdict(list)
    for i, e in enumerate(edges):
        incident[e["src"]].append(i)
        incident[e["dst"]].append(i)

    def port(symbol: str, edge_index: int) -> int:
        connected = incident[symbol]
        return int(positions[symbol] + NODE_H // 2 + (connected.index(edge_index) - (len(connected) - 1) / 2) * 14)

    right = NODE_X + NODE_W
    for i, e in enumerate(edges):
        rail = 472 + i * 23
        y1, y2 = port(e["src"], i), port(e["dst"], i)
        path = f"M {right} {y1} H {rail} V {y2} H {right}"
        paths.append(
            f'<path d="{path}" class="connector" marker-end="url(#arrow)" '
            f'data-claim-id="{esc(e["id"])}" data-query-ids="{esc(",".join(e["queries"]))}" '
            f'data-plane="static" data-coverage="{esc(e["coverage"])}">'
            f'<title>{esc(e["src"])} → {esc(e["dst"])} · {esc(e["kind"])}</title></path>'
        )
    for i, n in enumerate(nodes):
        y = positions[n["symbol"]]
        shared = terms.get(n["symbol"], {})
        visible_name = shared.get("label", n["symbol"])
        text = "".join(f'<text class="node-name" x="{NODE_X + 18}" y="{y + 29 + j * 18}">{esc(line)}</text>'
                       for j, line in enumerate(title_lines(visible_name)))
        if pattern == "dependencies":
            # Counts describe this SELECTED view, never a whole-repository fan-in.
            tag = f'{n["category"]} · IN {degrees[n["symbol"]][0]} / OUT {degrees[n["symbol"]][1]} (vista)'
        elif pattern == "traceability":
            tag = f'{n["category"]} · claim {n["id"]}'
            if len(tag) > 42:
                raise EditorialError("claim ID too long for visible traceability badge")
        else:
            tag = n["category"]
        focused = n["symbol"] == focus
        symbol_link = links.get(n["symbol"])
        node = (
            f'<g data-kind="component" data-symbol-id="{esc(n["symbol"])}" '
            f'data-claim-id="{esc(n["id"])}" data-query-ids="{esc(",".join(n["queries"]))}" '
            f'data-plane="static" data-coverage="{esc(n["coverage"])}" '
            f'data-context-id="{esc(shared.get("context_id", ""))}" '
            f'data-term-id="{esc(shared.get("term_id", ""))}" '
            f'data-term-status="{esc(shared.get("status", "unmapped"))}" '
            f'data-in-degree="{degrees[n["symbol"]][0]}" data-out-degree="{degrees[n["symbol"]][1]}" '
            f'data-focus="{str(focused).lower()}">'
            f'<title>{esc(visible_name)} — símbolo: {esc(n["symbol"])} · {esc(n["id"])} · consultas {esc(", ".join(n["queries"]))}</title>'
            f'<rect x="{NODE_X}" y="{y}" width="{NODE_W}" height="{NODE_H}" rx="6" class="node{" focal" if focused else ""}"/>'
            f'{text}<text class="node-tag" x="{NODE_X + 18}" y="{y + 68}">{esc(tag)}</text>'
            f'</g>'
        )
        # SVG2 links work in standalone SVG and embedded HTML, without JS.
        boxes.append((f'<a class="node-link" href="{esc(symbol_link)}" '
                      f'aria-label="Abrir ficha contextual de {esc(visible_name)}">{node}</a>')
                     if symbol_link else node)
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" role="img" aria-labelledby="editorial-title editorial-desc"
 viewBox="0 0 {WIDTH} {height}" width="{WIDTH}" height="{height}">
<title id="editorial-title">{esc(label)}</title>
<desc id="editorial-desc">C4 static architecture projection ({esc(pattern)}) based on {len(nodes)} selected entity claims and {len(edges)} relation claims; {esc(status)}. Ordering is visual, not execution order. Dependency counts are local to this view.</desc>
<style>
  .node {{fill:{colors["surface"]};stroke:{colors["stroke"]};stroke-width:1.3}}
  .node.focal {{stroke-width:3;stroke-dasharray:6 2}}
  .node-link {{cursor:pointer}}
  .node-link .node-name {{text-decoration:underline}}
  .node-link:focus .node {{stroke-width:3}}
  .connector {{fill:none;stroke:{colors["connector"]};stroke-width:1.5}}
  .node-name {{fill:{colors["ink"]};font:600 14px system-ui,sans-serif}}
  .node-tag {{fill:{colors["muted"]};font:11px ui-monospace,monospace}}
  .meta {{fill:{colors["muted"]};font:12px system-ui,sans-serif}}
  .headline {{fill:{colors["ink"]};font:600 23px system-ui,sans-serif}}
</style>
<defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M 0 0 L 8 4 L 0 8 Z" fill="{colors["connector"]}"/></marker></defs>
<rect width="{WIDTH}" height="{height}" fill="{colors["paper"]}"/>
<text x="56" y="60" class="headline">{esc(label)}</text>
<text x="56" y="86" class="meta">C4 · {esc(pattern)} · static evidence · {esc(status)}</text>
<text x="56" y="110" class="meta">Layout is not execution order; open the atlas for sources and coverage.</text>
{''.join(paths)}
{''.join(boxes)}
</svg>"""
    rows = "".join(
        f'<tr><td>{esc(e["src"])}</td><td>{esc(e["kind"])}</td><td>{esc(e["dst"])}</td>'
        f'<td><code>{esc(e["id"])}</code> · {esc(e["coverage"])}</td></tr>' for e in edges
    )
    node_rows = "".join(
        f'<tr><td><code>{esc(n["symbol"])}</code></td>'
        f'<td>{esc(terms.get(n["symbol"], {}).get("label", "Sin término compartido"))}'
        + (f' · <a rel="noopener" href="{esc(links[n["symbol"]])}">Abrir ficha</a>'
           if n["symbol"] in links else "") +
        f'</td><td><code>{esc(n["id"])}</code></td>'
        f'<td>{esc(", ".join(n["queries"]))}</td><td>{esc(n["coverage"])}</td></tr>'
        for n in nodes
    )
    html = f"""{MARKER}
<!doctype html><html lang="es"><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(label)} — CogniCode editorial</title>
<style>body{{margin:0;background:{colors["paper"]};color:{colors["ink"]};font:15px system-ui,sans-serif}}
main{{max-width:1080px;margin:32px auto;padding:0 22px}}
.diagram{{max-width:100%;overflow-x:auto;border:1px solid #dddcd8}}
.diagram svg{{display:block;min-width:{WIDTH}px;max-width:none}}
h2{{font-size:18px}}table{{border-collapse:collapse;width:100%;table-layout:fixed}}
td,th{{border-bottom:1px solid #d5d5d0;padding:10px;text-align:left;overflow-wrap:anywhere}}
small{{color:{colors["muted"]}}}@media print{{.diagram{{overflow:visible}}.diagram svg{{min-width:0;width:100%;height:auto}}}}</style>
</head><body><main><div class="diagram">{svg}</div>
<h2>Relaciones demostradas en la vista</h2>
<table><thead><tr><th>Origen</th><th>Relación</th><th>Destino</th><th>Evidencia</th></tr></thead>
<tbody>{rows}</tbody></table>
<h2>Evidencia de componentes</h2>
<table><thead><tr><th>Símbolo técnico</th><th>Nombre común y ficha</th><th>Claim</th><th>Consultas CogniCode</th><th>Cobertura</th></tr></thead>
<tbody>{node_rows}</tbody></table>
<p><small>{esc(status)}. SVG/HTML are visual projections, not verification of current code.
Symbols, relations and query IDs come solely from the existing CogniCode ledger; inspect the atlas to audit them.
Dependency IN/OUT metrics, if shown, count only the selected view, not the whole application.
The positional order has no runtime meaning. A common name is curated language, not independently proven implementation.</small></p></main></body></html>
"""
    return svg, html


def write_owned(path: Path, content: str, workspace: Path) -> None:
    safe(path, workspace)
    if path.exists() and (not path.is_file() or not path.read_text(encoding="utf-8").startswith(MARKER)):
        raise EditorialError("refusing to overwrite non-editorial artifact: " + str(path))
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    fd, temp = tempfile.mkstemp(prefix=".editorial-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.chmod(temp, 0o644)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def inspect(repo: Path, view_id: str, *, home: Path | None = None,
            profile: str = "default", pattern: str = "topology",
            focus: str | None = None, context: str | None = None) -> dict:
    if not VIEW_ID.fullmatch(view_id):
        raise EditorialError("invalid view ID")
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise EditorialError("derived workspace is not ready")
    workspace = Path(info["workspace"])
    label, nodes, edges, status = model(workspace, view_id)
    colors = profile_colors((home or Path.home()).expanduser().resolve(strict=True), profile)
    # Validate the actual projection, including focus and visual budget, without writing.
    terms, links = contextual_nodes(workspace, nodes, context, view_id)
    draw(label, nodes, edges, status, colors, pattern=pattern, focus=focus, terms=terms, links=links)
    targets = [workspace / "lenses" / "c4" / "renders" / (view_id + suffix)
               for suffix in (".editorial.svg", ".editorial.html")]
    for target in targets:
        safe(target, workspace)
        if target.exists() and (not target.is_file() or not target.read_text(encoding="utf-8").startswith(MARKER)):
            raise EditorialError("non-editorial output already exists: " + str(target))
    return {"status": "EDITORIAL_INPUT_READY", "view": view_id, "pattern": pattern,
            "profile": profile, "focus": focus, "context": context, "linked_nodes": len(links), "coverage": status,
            "entities": len(nodes), "relations": len(edges),
            "source": "cognicode-derived-ledger", "code_access": "none"}


def link_atlas(workspace: Path, view_id: str) -> bool:
    """Update only the previously validated derived view report, never product files."""
    report_path = safe(workspace / "lenses" / "c4" / "reports" / (view_id + ".atlas.json"), workspace)
    report = load(report_path, workspace)
    if not isinstance(report, dict) or not isinstance(report.get("assets"), list):
        raise EditorialError("invalid derived view report")
    extras = [f"lenses/c4/renders/{view_id}.editorial.svg",
              f"lenses/c4/renders/{view_id}.editorial.html"]
    assets = report["assets"]
    if any(not isinstance(x, str) for x in assets):
        raise EditorialError("invalid view assets")
    for extra in extras:
        if not (workspace / extra).is_file():
            raise EditorialError("editorial asset not generated: " + extra)
    additions = [extra for extra in extras if extra not in assets]
    if not additions:
        return False
    updated = dict(report, assets=assets + additions)
    fd, tmp = tempfile.mkstemp(prefix=".view-editorial-", dir=report_path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(updated, handle, ensure_ascii=False, indent=2)
            handle.write("\n")
        os.chmod(tmp, 0o600)
        os.replace(tmp, report_path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)
    return True


def render(repo: Path, view_id: str, *, home: Path | None = None,
           profile: str = "default", pattern: str = "topology",
           focus: str | None = None, link: bool = False,
           context: str | None = None) -> dict:
    if not VIEW_ID.fullmatch(view_id):
        raise EditorialError("invalid view ID")
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise EditorialError("derived workspace is not ready")
    workspace = Path(info["workspace"])
    label, nodes, edges, status = model(workspace, view_id)
    colors = profile_colors((home or Path.home()).expanduser().resolve(strict=True), profile)
    terms, links = contextual_nodes(workspace, nodes, context, view_id)
    svg, page = draw(label, nodes, edges, status, colors, pattern=pattern,
                     focus=focus, terms=terms, links=links)
    folder = safe(workspace / "lenses" / "c4" / "renders", workspace)
    if not folder.is_dir():
        raise EditorialError("C4 renders directory missing")
    svg_path = folder / (view_id + ".editorial.svg")
    html_path = folder / (view_id + ".editorial.html")
    # Check both targets before either write; never replace unrelated assets.
    for target in (svg_path, html_path):
        safe(target, workspace)
        if target.exists() and (not target.is_file() or not target.read_text(encoding="utf-8").startswith(MARKER)):
            raise EditorialError("non-editorial output already exists: " + str(target))
    write_owned(svg_path, MARKER + "\n" + svg + "\n", workspace)
    write_owned(html_path, page, workspace)
    linked = link_atlas(workspace, view_id) if link else False
    return {"status": "EDITORIAL_RENDERED", "profile": profile, "pattern": pattern,
            "focus": focus, "context": context, "linked_nodes": len(links), "atlas_linked": linked, "coverage": status, "entities": len(nodes),
            "relations": len(edges), "svg": str(svg_path), "html": str(html_path),
            "note": "Add both output paths to the existing <view>.atlas.json assets, then atlas.py sync"}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True, help="Explicit checkout root; identity only")
    parser.add_argument("--view", required=True, help="Existing C4 view report stem")
    parser.add_argument("--profile", default="default", help="Optional HOME presentation profile")
    parser.add_argument("--pattern", default="topology",
                        choices=("topology", "dependencies", "traceability"),
                        help="One evidence-preserving semantic presentation pattern")
    parser.add_argument("--focus", help="Exact CogniCode symbol_id in the selected view")
    parser.add_argument("--context", help="DDD context_id; no implicit merging of homonyms")
    parser.add_argument("--check", action="store_true", help="Validate inputs and budgets without writing")
    parser.add_argument("--link-atlas", action="store_true",
                        help="After rendering, add existing editorial assets to the derived view report")
    args = parser.parse_args(argv)
    try:
        if args.check and args.link_atlas:
            parser.error("--check and --link-atlas cannot be combined")
        result = (inspect(args.repo, args.view, profile=args.profile,
                          pattern=args.pattern, focus=args.focus, context=args.context)
                  if args.check else
                  render(args.repo, args.view, profile=args.profile,
                         pattern=args.pattern, focus=args.focus, link=args.link_atlas,
                         context=args.context))
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (EditorialError, OSError) as exc:
        print(json.dumps({"status": "PARTIAL", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
