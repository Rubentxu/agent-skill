def paths(root: Path, data: dict) -> tuple[Path, Path]:
    # A symbol can have different meanings in different bounded contexts.
    # Keep the old unscoped digest stable, but avoid overwriting scoped passports.
    context = data.get("requested_context")
    identity = data["kind"] + "\0" + data["target_id"]
    if context is not None and data["kind"] in {"symbol-passport", "change-impact"}:
        identity += "\0context:" + context
    if data["kind"] == "change-impact":
        identity += "\0goal:" + data["change"]["goal"]
    digest = hashlib.sha256(identity.encode()).hexdigest()[:16]
    prefix = data["kind"] + "-" + digest
    folder = safe(root / "reports", root)
    return safe(folder / (prefix + ".report.json"), root), safe(folder / (prefix + ".report.md"), root)


def owned_write(path: Path, content: str, *, is_json: bool = False) -> None:
    if path.exists():
        try:
            prev = path.read_text(encoding="utf-8")
            valid = (json.loads(prev).get("generator") == GENERATOR if is_json else prev.startswith(MARKER))
        except (ValueError, AttributeError, UnicodeError):
            valid = False
        if not valid:
            raise ReportError("unowned report output refused: " + path.name)
        if prev == content:
            return
    fd, temp = tempfile.mkstemp(dir=path.parent, prefix=".report-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as out:
            out.write(content)
        os.chmod(temp, 0o644)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def build(repo: Path, kind: str, *, symbol: str | None = None,
          context: str | None = None, term: str | None = None,
          goal: str | None = None, home: Path | None = None, check: bool = False) -> dict:
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise ReportError("external CogniCode workspace not ready")
    root = Path(info["workspace"])
    data = project(root, kind, symbol=symbol, context=context, term=term, goal=goal)
    jpath, mpath = paths(root, data)
    if check:
        return {"status": "EVIDENCE_READY", "kind": kind, "scope": data["status"],
                "claim_count": len(data["evidence"]["claim_ids"]), "language": data["language"],
                "note": "Checks derived records; cannot prove CogniCode runtime authenticity."}
    safe(jpath.parent, root).mkdir(exist_ok=True)
    # Validate ownership of both outputs BEFORE changing either.
    for path, is_json in ((jpath, True), (mpath, False)):
        if path.exists():
            prev = path.read_text(encoding="utf-8")
            if not (json.loads(prev).get("generator") == GENERATOR if is_json and prev.lstrip().startswith("{")
                    else prev.startswith(MARKER) if not is_json else False):
                raise ReportError("unowned report output refused: " + path.name)
    serialized = json.dumps(data, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    owned_write(jpath, serialized, is_json=True)
    owned_write(mpath, markdown(data))
    return {"status": data["status"], "kind": kind, "json": str(jpath), "markdown": str(mpath),
            "claim_count": len(data["evidence"]["claim_ids"]),
            "note": "Run atlas.py sync to link reports; not a code-quality certification."}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--kind", choices=("term-card", "symbol-passport", "change-impact"), required=True)
    parser.add_argument("--symbol")
    parser.add_argument("--context")
    parser.add_argument("--term")
    parser.add_argument("--goal", help="Specific intended change (user request), not code evidence")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        result = build(args.repo, args.kind, symbol=args.symbol, context=args.context,
                       term=args.term, goal=args.goal, check=args.check)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (ReportError, OSError, ValueError) as exc:
        print(json.dumps({"status": "BLOCKED", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
