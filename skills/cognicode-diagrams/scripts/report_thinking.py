#!/usr/bin/env python3
"""Moldable Term Card / Symbol Passport / Change Impact Brief from CogniCode-derived ledgers ONLY.

Never opens or scans the target checkout, calls Git, runs CogniCode, or creates
business semantics. This is a presentation projector over prior structured evidence.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile

from workspace import inspect as inspect_workspace

SLUG = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*\Z")
MAX_INPUT = 2 * 1024 * 1024
MAX_RECORDS = 500
GENERATOR = "cognicode-diagrams-report-v1"
MARKER = "<!-- Generated by cognicode-diagrams report_thinking.py v1. -->"
STATUSES = {"candidate", "accepted", "disputed", "deprecated"}


class ReportError(ValueError):
    """Unsafe or insufficient derived evidence."""


def text(value, label: str, limit: int = 400) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > limit or any(
        ord(c) < 32 and c not in "\n\t" for c in value
    ):
        raise ReportError("invalid " + label)
    return value.strip()


def slug(value, label: str) -> str:
    if not isinstance(value, str) or len(value) > 80 or not SLUG.fullmatch(value):
        raise ReportError("invalid " + label)
    return value


def safe(path: Path, root: Path) -> Path:
    if not path.is_relative_to(root):
        raise ReportError("path outside derived workspace")
    for part in (path, *path.parents):
        if part == root.parent:
            break
        if part.is_symlink():
            raise ReportError("symlink in derived workspace")
    return path


def load(path: Path, root: Path, *, optional: bool = False):
    safe(path, root)
    if optional and not path.exists():
        return []
    if not path.is_file() or path.stat().st_size > MAX_INPUT:
        raise ReportError("missing or oversized derived input: " + path.name)
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeError) as exc:
        raise ReportError("invalid derived JSON: " + path.name) from exc


def items(raw, key: str) -> list:
    if isinstance(raw, dict):
        raw = raw.get(key)
    if not isinstance(raw, list) or len(raw) > MAX_RECORDS:
        raise ReportError(key + " must be a bounded array")
    return raw


def indexed(raw, key: str, identity: str) -> dict:
    output = {}
    for record in items(raw, key):
        if not isinstance(record, dict):
            raise ReportError("invalid " + key + " entry")
        rid = record.get(identity, record.get("id"))
        rid = text(rid, key + " ID")
        if rid in output:
            raise ReportError("duplicate " + key + " ID: " + rid)
        output[rid] = record
    return output


def vocab(root: Path) -> dict:
    """Vocabulary is curated/proposed language, not an observation of code."""
    raw = load(root / "evidence" / "terms.json", root, optional=True)
    terms = {}
    for item in items(raw, "terms"):
        if not isinstance(item, dict):
            raise ReportError("invalid term")
        context = slug(item.get("context_id"), "context_id")
        term = slug(item.get("term_id"), "term_id")
        ident = (context, term)
        if ident in terms:
            raise ReportError("duplicate term in context")
        status = item.get("status", "candidate")
        if status not in STATUSES:
            raise ReportError("invalid term status")
        label = text(item.get("label"), "term label", 120)
        definition = text(item.get("definition"), "definition", 600)
        symbols = item.get("symbol_ids", [])
        if not isinstance(symbols, list) or len(symbols) > 30 or len(set(map(str, symbols))) != len(symbols):
            raise ReportError("invalid term symbol bindings")
        symbols = [text(x, "term symbol") for x in symbols]
        curator = item.get("curator")
        if status == "accepted":
            curator = text(curator, "accepted term curator", 120)
        elif curator is not None:
            curator = text(curator, "curator", 120)
        terms[ident] = {
            "context_id": context, "term_id": term, "label": label,
            "definition": definition, "status": status,
            "curator": curator, "symbol_ids": symbols,
            "not_this": text(item["not_this"], "not_this", 320) if "not_this" in item else None
        }
    return terms


def evidence(root: Path) -> tuple[dict, dict, dict]:
    queries = indexed(load(root / "evidence" / "queries.json", root), "queries", "query_id")
    claims = indexed(load(root / "evidence" / "claims.json", root), "claims", "claim_id")
    entities, relations = {}, {}
    for cid, claim in claims.items():
        if claim.get("provenance", claim.get("status")) not in {"OBSERVED_CODE", "observed"}:
            continue  # Intention/inference never establishes implementation.
        if claim.get("plane", "static") != "static" or claim.get("category") == "intent":
            continue
        qids = claim.get("query_ids")
        if not isinstance(qids, list) or not qids or len(set(qids)) != len(qids):
            raise ReportError("code claim missing or duplicate query IDs: " + cid)
        if any(qid not in queries for qid in qids):
            raise ReportError("code claim references missing query: " + cid)
        selected = [queries[q] for q in qids]
        relevant = [
            q for q in selected
            if q.get("mode") in {"structured", "symbol_context"}
            and q.get("status") in {"ok", "partial"}
            and q.get("observation_plane", "static") == "static"
            and q.get("source", "cognicode") == "cognicode"
        ]
        coverage = claim.get("coverage", "unknown")
        if coverage not in {"complete", "partial", "unknown"}:
            raise ReportError("invalid claim coverage: " + cid)
        base = {"claim_id": cid, "query_ids": qids, "coverage": coverage, "plane": "static"}
        if claim.get("kind", "entity") == "entity":
            symbol = text(claim.get("symbol_id"), "entity symbol")
            if not any(symbol in q.get("symbol_ids", []) for q in relevant if isinstance(q.get("symbol_ids"), list)):
                raise ReportError("entity not corroborated by CogniCode query: " + cid)
            entities.setdefault(symbol, []).append({
                **base, "category": claim.get("category", "symbol")
            })
        elif claim.get("kind") == "relation" and claim.get("relation_source") == "graph_edge":
            src = text(claim.get("from_symbol"), "from_symbol")
            dst = text(claim.get("to_symbol"), "to_symbol")
            rel = text(claim.get("relation_id"), "relation_id")
            if not any(
                q.get("mode") == "structured"
                and isinstance(q.get("symbol_ids"), list)
                and isinstance(q.get("relation_ids"), list)
                and src in q["symbol_ids"] and dst in q["symbol_ids"]
                and rel in q["relation_ids"] for q in relevant
            ):
                raise ReportError("relation not corroborated by CogniCode query: " + cid)
            attrs = claim.get("attributes", {})
            if not isinstance(attrs, dict):
                raise ReportError("invalid relation attributes: " + cid)
            relations[cid] = {
                **base, "from_symbol": src, "to_symbol": dst,
                "relation_id": rel,
                "kind": text(attrs.get("kind", "relation"), "relation kind", 120)
            }
        # reference_link is NOT a call-graph edge; do not depict it as such.
    return queries, entities, relations


def basis_of(queries: dict, ids: set[str]) -> dict:
    """No guessed SHA or currency: only matching identities supplied by CogniCode."""
    values = {queries[i].get("basis") for i in ids if isinstance(queries[i].get("basis"), str)}
    if not values:
        return {"identity": None, "status": "unknown"}
    if len(values) != 1:
        return {"identity": None, "status": "conflict"}
    return {"identity": next(iter(values)), "status": "reported_unverified"}


def project(root: Path, kind: str, *, symbol: str | None = None,
            context: str | None = None, term: str | None = None,
            goal: str | None = None) -> dict:
    if kind not in {"term-card", "symbol-passport", "change-impact"}:
        raise ReportError("unknown report kind")
    if kind == "change-impact":
        goal = text(goal, "change goal", 240)
        if "\n" in goal or "\t" in goal:
            raise ReportError("change goal must be one line")
    elif goal is not None:
        raise ReportError("--goal only valid for change-impact")
    queries, entities, relations = evidence(root)
    terms = vocab(root)
    selected_term = None
    if kind == "term-card":
        if context is None or term is None or symbol is not None:
            raise ReportError("term-card requires --context and --term, not --symbol")
        selected_term = terms.get((slug(context, "context"), slug(term, "term")))
        if selected_term is None:
            raise ReportError("unknown contextual term; propose it in HOME evidence/terms.json")
        target_symbols = selected_term["symbol_ids"]
        target_id = selected_term["context_id"] + ":" + selected_term["term_id"]
    else:
        if symbol is None or term is not None:
            raise ReportError("symbol-passport/change-impact requires --symbol and optional --context")
        symbol = text(symbol, "symbol_id")
        if symbol not in entities:
            raise ReportError("symbol lacks corroborated CogniCode entity evidence")
        if context is not None:
            slug(context, "context")
        target_symbols = [symbol]
        target_id = symbol
    matched = [t for t in terms.values()
               if any(s in target_symbols for s in t["symbol_ids"])
               and (context is None or t["context_id"] == context)]
    matched.sort(key=lambda t: (t["context_id"], t["term_id"]))
    term_view = selected_term if selected_term is not None else (matched[0] if len(matched) == 1 else None)
    claims = [c for s in target_symbols for c in entities.get(s, [])]
    edges = [r for r in relations.values()
             if r["from_symbol"] in target_symbols or r["to_symbol"] in target_symbols]
    edges.sort(key=lambda x: x["claim_id"])
    # A budget is explicit. Never imply we returned the entire graph.
    shown = edges[:12]
    truncated = len(edges) > len(shown)
    claim_ids = sorted({c["claim_id"] for c in claims + shown})
    query_ids = sorted({q for c in claims + shown for q in c["query_ids"]})
    complete = (bool(claims) and all(c["coverage"] == "complete" for c in claims + shown)
                and not truncated and basis_of(queries, set(query_ids))["status"] != "conflict")
    label = term_view["label"] if term_view else target_id
    language = {
        "label": label, "context_id": term_view["context_id"] if term_view else None,
        "term_id": term_view["term_id"] if term_view else None,
        "status": term_view["status"] if term_view else "unmapped",
        "definition": term_view["definition"] if term_view else None,
        "definition_authority": ("HUMAN_CURATED" if term_view and term_view["status"] == "accepted"
                                 else "PROPOSED" if term_view else "UNKNOWN"),
        "not_this": term_view["not_this"] if term_view else None,
        "alternative_contexts": [
            {"context_id": t["context_id"], "term_id": t["term_id"], "label": t["label"],
             "status": t["status"]} for t in matched
        ] if len(matched) > 1 else []
    }
    output = {
        "generator": GENERATOR, "schema_version": 1, "kind": kind, "target_id": target_id,
        "requested_context": context,
        "symbol_ids": target_symbols, "language": language,
        "beginner": {
            "what": (term_view["definition"] if term_view else
                     "Símbolo técnico identificado por CogniCode; finalidad de negocio desconocida."),
            "why": ("Definición del dominio aportada por una persona."
                    if language["definition_authority"] == "HUMAN_CURATED" else
                    "Explicación propuesta, no demostración de comportamiento."
                    if term_view else "Consultar contexto del símbolo para explicar su responsabilidad."),
            "how_we_know": "Relaciones y símbolos proceden únicamente de consultas estructuradas CogniCode.",
            "what_we_do_not_know": (
                "La equivalencia entre este término y el código no está demostrada."
                if not claims else "La ejecución real y los efectos runtime no están acreditados por un grafo estático.")
        },
        "evidence": {
            "origin": "cognicode", "plane": "static",
            "basis": basis_of(queries, set(query_ids)),
            "coverage": "scoped" if complete else "partial_or_unknown",
            "claim_ids": claim_ids, "query_ids": query_ids,
            "entities": claims, "relations": shown,
            "related_total": len(edges), "related_truncated": truncated,
            "unverified_symbol_ids": sorted(s for s in target_symbols if s not in entities)
        },
        "status": "GROUNDED_SCOPED" if claims else "LANGUAGE_ONLY",
        "certification": "derived-presentation-not-runtime-verification"
    }
    if kind == "change-impact":
        # Direction is CORROBORATED; whether the change affects any neighbour
        # is a HYPOTHESIS, never a semantic or runtime conclusion.
        incoming = [r for r in shown if r["to_symbol"] == symbol]
        outgoing = [r for r in shown if r["from_symbol"] == symbol]
        unknown = ["No se ha demostrado qué comportamientos modifica la petición.",
                   "El grafo estático no demuestra impacto runtime ni compatibilidad.",
                   "La lista solo cubre las relaciones corroboradas en el ledger disponible."]
        if truncated:
            unknown.append("Se omitieron relaciones por el presupuesto de presentación.")
        if not incoming:
            unknown.append("No encontrar relaciones entrantes aquí NO demuestra ausencia de consumidores.")
        if not outgoing:
            unknown.append("No encontrar relaciones salientes aquí NO demuestra independencia.")
        output["change"] = {
            "goal": goal,
            "question_status": "USER_INTENT_NOT_CODE_EVIDENCE",
            "observed_incoming": incoming, "observed_outgoing": outgoing,
            "potentially_affected": [
                {"symbol_id": r["from_symbol"], "relation_claim_id": r["claim_id"],
                 "status": "HYPOTHESIS_NOT_VALIDATED"}
                for r in incoming
            ],
            "unknowns": unknown,
            "next_questions": [
                {"question": "¿Qué consumidores y referencias estructuradas tiene el símbolo en el ámbito pertinente?",
                 "purpose": "Confirmar el alcance de relaciones entrantes y omisiones",
                 "authority": "cognicode-only"},
                {"question": "¿Qué contratos y usos del símbolo condicionan el cambio solicitado?",
                 "purpose": "Investigar compatibilidad sin inferirla de las aristas",
                 "authority": "cognicode-only"},
                {"question": "¿Qué rutas de error o estados importantes se asocian al comportamiento que se pretende modificar?",
                 "purpose": "Acotar verificaciones quirúrgicas antes de editar",
                 "authority": "cognicode-only"}
            ],
            "readiness": ("PARTIAL_RESEARCH_REQUIRED" if truncated or
                          output["evidence"]["coverage"] != "scoped" or
                          output["evidence"]["basis"]["status"] != "reported_unverified"
                          else "SCOPED_STATIC_EVIDENCE_ONLY"),
            "edit_authorized": False,
            "impact_verified": False
        }
    return output


def markdown(data: dict) -> str:
    v, e, beginner = data["language"], data["evidence"], data["beginner"]
    # All untrusted text must be literal; never let terms inject Markdown links, HTML or instructions.
    def literal(s) -> str:
        if s is None:
            return "No disponible"
        return str(s).replace("\\", "\\\\").replace("<", "&lt;").replace(">", "&gt;").replace(
            "[", "\\[").replace("]", "\\]").replace("*", "\\*").replace("_", "\\_").replace(
            "`", "\\`").replace("|", "\\|").replace("\n", " ")
    lines = [
        MARKER,
        "# " + literal(v["label"]), "",
        "**Tipo:** " + {"term-card": "Ficha de término", "symbol-passport": "Pasaporte de símbolo", "change-impact": "Informe de preparación de cambio"}[data["kind"]],
        "**Contexto:** " + literal(v["context_id"]),
        "**Término:** " + literal(v["term_id"]),
        "**Estado del nombre:** " + literal(v["status"]),
        "**Procedencia del significado:** " + literal(v["definition_authority"]), "",
        "## ¿Qué es?", "", literal(beginner["what"]), "",
        "## ¿Por qué importa?", "", literal(beginner["why"]), "",
        "## ¿Cómo lo sabemos?", "",
        "Identidad técnica: " + ", ".join("`" + literal(s) + "`" for s in data["symbol_ids"]),
        "Claims: " + ", ".join(literal(s) for s in e["claim_ids"]),
        "Consultas CogniCode: " + ", ".join(literal(s) for s in e["query_ids"]),
        "Cobertura: " + literal(e["coverage"]),
        "Versión: " + literal(e["basis"]["identity"]) + " (" + literal(e["basis"]["status"]) + ")", "",
        "## Relaciones estáticas acreditadas", ""
    ]
    if e["relations"]:
        for r in e["relations"]:
            lines.append("- " + literal(r["from_symbol"]) + " → " + literal(r["to_symbol"]) +
                         " (" + literal(r["kind"]) + "; claim " + literal(r["claim_id"]) + ")")
    else:
        lines.append("No hay relaciones acreditadas en esta ficha.")
    lines += [
        "", "## ¿Qué desconocemos?", "", literal(beginner["what_we_do_not_know"]), "",
        "Una relación estática no demuestra orden temporal ni comportamiento en ejecución.",
        "La vigencia de la revisión debe corroborarse con CogniCode.",
        "La aceptación humana de un término no prueba que el código lo implemente.", ""
    ]
    if e["related_truncated"]:
        lines.append("**Aviso:** se muestran solo 12 de " + str(e["related_total"]) +
                     " relaciones corroboradas. Ampliar por consulta focalizada.\n")
    if v["alternative_contexts"]:
        lines.extend(["## Términos de otros contextos", ""])
        for a in v["alternative_contexts"]:
            lines.append("- " + literal(a["context_id"]) + ": " + literal(a["label"]) +
                         " (" + literal(a["status"]) + ")")
    if data["kind"] == "change-impact":
        change = data["change"]
        # The goal is user intent, NOT proof of the code behaviour.
        lines += ["", "## Cambio solicitado (intención del usuario)", "",
                  literal(change["goal"]), "",
                  "## Relaciones entrantes observadas (posibles consumidores)", ""]
        lines += (["- " + literal(r["from_symbol"]) + " → " + literal(r["to_symbol"]) +
                   " (claim " + literal(r["claim_id"]) + "; consulta " +
                   literal(", ".join(r["query_ids"])) + ")" for r in change["observed_incoming"]]
                  or ["Ninguna observada en el ámbito disponible. **NO significa que no haya consumidores.**"])
        lines += ["", "## Relaciones salientes observadas (colaboradores)", ""]
        lines += (["- " + literal(r["from_symbol"]) + " → " + literal(r["to_symbol"]) +
                   " (claim " + literal(r["claim_id"]) + ")" for r in change["observed_outgoing"]]
                  or ["Ninguna observada en este ámbito; no implica independencia."])
        lines += ["", "## Hipótesis, NO fallos demostrados", ""]
        lines += (["- Podría necesitar revisión: " + literal(h["symbol_id"]) +
                   " (relación " + literal(h["relation_claim_id"]) + ")."
                   for h in change["potentially_affected"]]
                  or ["No se identificaron candidatos en las relaciones entrantes observadas."])
        lines += ["", "## Qué preguntar a CogniCode antes de modificar", ""]
        lines += ["- " + literal(q["question"]) + " — " + literal(q["purpose"])
                  for q in change["next_questions"]]
        lines += ["", "## Límites y decisión", ""]
        lines += ["- " + literal(x) for x in change["unknowns"]]
        lines += ["", "Preparación: " + literal(change["readiness"]),
                  "Edición autorizada por este informe: **NO**.",
                  "Impacto real verificado: **NO**.",
                  "Utilizar pruebas afectadas/contratos solo después de investigar el cambio con CogniCode.", ""]
    return "\n".join(lines).rstrip() + "\n"


def paths(root: Path, data: dict) -> tuple[Path, Path]:
    # A symbol can have different meanings in different bounded contexts.
    # Keep the old unscoped digest stable, but avoid overwriting scoped passports.
    context = data.get("requested_context")
    identity = data["kind"] + "\0" + data["target_id"]
    if context is not None and data["kind"] in {"symbol-passport", "change-impact"}:
        identity += "\0context:" + context
    if data["kind"] == "change-impact":
        identity += "\0goal:" + data["change"]["goal"]
    digest = hashlib.sha256(identity.encode()).hexdigest()[:16]
    prefix = data["kind"] + "-" + digest
    folder = safe(root / "reports", root)
    return safe(folder / (prefix + ".report.json"), root), safe(folder / (prefix + ".report.md"), root)


def owned_write(path: Path, content: str, *, is_json: bool = False) -> None:
    if path.exists():
        try:
            prev = path.read_text(encoding="utf-8")
            valid = (json.loads(prev).get("generator") == GENERATOR if is_json else prev.startswith(MARKER))
        except (ValueError, AttributeError, UnicodeError):
            valid = False
        if not valid:
            raise ReportError("unowned report output refused: " + path.name)
        if prev == content:
            return
    fd, temp = tempfile.mkstemp(dir=path.parent, prefix=".report-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as out:
            out.write(content)
        os.chmod(temp, 0o644)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def build(repo: Path, kind: str, *, symbol: str | None = None,
          context: str | None = None, term: str | None = None,
          goal: str | None = None, home: Path | None = None, check: bool = False) -> dict:
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise ReportError("external CogniCode workspace not ready")
    root = Path(info["workspace"])
    data = project(root, kind, symbol=symbol, context=context, term=term, goal=goal)
    jpath, mpath = paths(root, data)
    if check:
        return {"status": "EVIDENCE_READY", "kind": kind, "scope": data["status"],
                "claim_count": len(data["evidence"]["claim_ids"]), "language": data["language"],
                "note": "Checks derived records; cannot prove CogniCode runtime authenticity."}
    safe(jpath.parent, root).mkdir(exist_ok=True)
    # Validate ownership of both outputs BEFORE changing either.
    for path, is_json in ((jpath, True), (mpath, False)):
        if path.exists():
            prev = path.read_text(encoding="utf-8")
            if not (json.loads(prev).get("generator") == GENERATOR if is_json and prev.lstrip().startswith("{")
                    else prev.startswith(MARKER) if not is_json else False):
                raise ReportError("unowned report output refused: " + path.name)
    serialized = json.dumps(data, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    owned_write(jpath, serialized, is_json=True)
    owned_write(mpath, markdown(data))
    return {"status": data["status"], "kind": kind, "json": str(jpath), "markdown": str(mpath),
            "claim_count": len(data["evidence"]["claim_ids"]),
            "note": "Run atlas.py sync to link reports; not a code-quality certification."}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--kind", choices=("term-card", "symbol-passport", "change-impact"), required=True)
    parser.add_argument("--symbol")
    parser.add_argument("--context")
    parser.add_argument("--term")
    parser.add_argument("--goal", help="Specific intended change (user request), not code evidence")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        result = build(args.repo, args.kind, symbol=args.symbol, context=args.context,
                       term=args.term, goal=args.goal, check=args.check)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (ReportError, OSError, ValueError) as exc:
        print(json.dumps({"status": "BLOCKED", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
