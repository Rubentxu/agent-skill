#!/usr/bin/env python3
"""Create a navigable Markdown atlas from existing diagram artifacts only.

NEVER reads the Git working tree content; NEVER runs CogniCode or projectors.
The atlas is a derived knowledge navigation projection, not another analysis engine.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path
from urllib.parse import quote

from workspace import WorkspaceError, VALID_LENS, inspect as inspect_workspace
from knowledge_atlas import KnowledgeError, fingerprints as knowledge_fingerprints, project as project_knowledge

IMAGE_EXT = {".svg", ".png", ".webp"}
SOURCE_EXT = {".dsl", ".mmd", ".puml", ".c4", ".likec4", ".d2", ".md"}
MAX_FILES = 300
MAX_BYTES = 16 * 1024 * 1024
MARKER = "<!-- Generated by cognicode-diagrams atlas.py. Do not edit: regenerate from lens assets. -->"


class AtlasError(ValueError):
    """Invalid or unsafe atlas inputs."""


def _inside(path: Path, workspace: Path) -> bool:
    if path.is_symlink() or not path.resolve(strict=True).is_relative_to(workspace):
        return False
    # All components from the workspace down must be regular paths, not symlinks.
    return all(not x.is_symlink() for x in (path, *list(path.parents)[:len(path.parts) - len(workspace.parts)]))


def _items(folder: Path, extensions: set[str], workspace: Path) -> list[Path]:
    if not folder.exists():
        return []
    if folder.is_symlink() or not folder.is_dir() or not _inside(folder, workspace):
        raise AtlasError(f"carpeta de artefactos insegura: {folder}")
    files = []
    for p in sorted(folder.iterdir()):
        if p.is_symlink():
            raise AtlasError(f"enlace simbólico dentro de artefactos: {p}")
        if p.is_file() and p.suffix.lower() in extensions:
            if not _inside(p, workspace) or p.stat().st_size > MAX_BYTES:
                raise AtlasError(f"archivo fuera del workspace o demasiado grande: {p}")
            files.append(p)
    return files


def _label(name: str) -> str:
    # Eliminate Markmap/Markdown injection via untrusted filenames.
    return re.sub(r"[\[\]()*_`!<>|\\\r\n]", " ", name).strip()[:100] or "diagrama"


def _href(source: Path, navigation: Path) -> str:
    relative = os.path.relpath(source, navigation)
    return quote(relative.replace(os.sep, "/"), safe="/.-_~")


def _hash(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        while part := handle.read(65536):
            h.update(part)
    return h.hexdigest()


def _write_owned(path: Path, content: str, marker: str) -> None:
    if path.is_symlink():
        raise AtlasError("el archivo de destino es un enlace simbólico")
    if path.exists() and not path.read_text(encoding="utf-8").startswith(marker):
        raise AtlasError(f"archivo preexistente no generado por esta skill: {path}")
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    fd, temp = tempfile.mkstemp(dir=path.parent, prefix=".atlas-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
        os.chmod(temp, 0o644)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def _manifest_write(path: Path, data: dict) -> None:
    if path.is_symlink() or (path.exists() and json.loads(path.read_text(encoding="utf-8")).get("generator") != "cognicode-diagrams-atlas"):
        raise AtlasError("manifiesto preexistente no gestionado")
    content = json.dumps(data, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    fd, temp = tempfile.mkstemp(dir=path.parent, prefix=".atlas-manifest-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
        os.chmod(temp, 0o644)
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


def assets(workspace: Path) -> dict[str, dict[str, list[Path]]]:
    root = workspace / "lenses"
    if root.is_symlink() or not root.is_dir() or not _inside(root, workspace):
        raise AtlasError("lenses es inseguro o no existe")
    result: dict[str, dict[str, list[Path]]] = {}
    n = 0
    for lens in sorted(root.iterdir()):
        if lens.is_symlink():
            raise AtlasError(f"lente enlazada no permitida: {lens}")
        if not lens.is_dir():
            continue
        if not VALID_LENS.fullmatch(lens.name) or not _inside(lens, workspace):
            raise AtlasError(f"lente insegura: {lens}")
        source = _items(lens / "sources", SOURCE_EXT, workspace)
        renders = _items(lens / "renders", IMAGE_EXT, workspace)
        if source or renders:
            n += len(source) + len(renders)
            if n > MAX_FILES:
                raise AtlasError("demasiados archivos; dividir el atlas por alcance")
            result[lens.name] = {"sources": source, "renders": renders}
    return result


def discover_viewers(repo: Path, lenses: list[str], engine: str | None, home: Path | None) -> dict[str, list[str]]:
    """Read-only inspection of our own labeled local projectors; never start them."""
    try:
        from projectors import engine_binary, params, status
        binary = engine_binary(engine)
    except (ImportError, ValueError):
        return {}
    urls: dict[str, list[str]] = {}
    for lens in lenses:
        for projector in ("likec4", "structurizr"):
            try:
                p = params(repo, projector, lens=lens, home=home)
                info = status(binary, p, check_http=True)
                if info["status"] == "ready" and info.get("url", "").startswith("http://127.0.0.1:"):
                    urls.setdefault(lens, []).append(f"[{projector} local]({info['url']})")
            except (ValueError, OSError):
                continue
    return urls


def build(repo: Path, *, home: Path | None = None, inspect_viewers: bool = False,
          engine: str | None = None, embed_images: bool = True) -> dict:
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise AtlasError("workspace externo no preparado; ejecutar scripts/workspace.py init")
    workspace = Path(info["workspace"])
    nav = workspace / "navigation"
    if nav.is_symlink() or (nav.exists() and not nav.is_dir()):
        raise AtlasError("directorio navigation inseguro")
    catalog = assets(workspace)
    knowledge_lines, knowledge_hashes, claim_count, view_count = project_knowledge(workspace, catalog, _href, _label)
    if not catalog and not claim_count:
        raise AtlasError("no hay diagramas ni claims CogniCode; registrar evidencia primero")
    links = discover_viewers(repo, list(catalog), engine, home) if inspect_viewers else {}
    if nav.exists() and not _inside(nav, workspace):
        raise AtlasError("directorio de navegación fuera del workspace")
    # A root created by the workspace resolver must not contain preexisting symlinks.
    nav.mkdir(exist_ok=True)
    lines = [MARKER, "# Atlas de " + _label(Path(info["repository"]).name), "", 
             "Mapa de **artefactos existentes**, no prueba de fidelidad arquitectónica.",
             "Los enlaces a visores interactivos solo funcionan mientras sus servicios locales sigan activos.", ""]
    lines.extend(knowledge_lines)
    metadata = {}
    for lens, listing in catalog.items():
        lines += ["## " + _label(lens), ""]
        metadata[lens] = {}
        for kind in ("sources", "renders"):
            for p in listing[kind]:
                metadata[lens][str(p.relative_to(workspace))] = _hash(p)
        if listing["renders"]:
            lines.append("- Vistas")
            for i, p in enumerate(listing["renders"]):
                url = _href(p, nav)
                title = _label(p.stem)
                lines.append(f"  - [{title} · {p.suffix[1:].upper()}]({url})")
                if embed_images and i == 0:
                    lines.append(f"    - ![{title}]({url})")
        if listing["sources"]:
            lines.append("- Fuentes editables")
            for p in listing["sources"]:
                lines.append(f"  - [{_label(p.name)}]({_href(p, nav)})")
        if lens in links:
            lines.append("- Visores locales disponibles")
            for url in links[lens]:
                lines.append("  - " + url)
        lines.append("")
    result = "\n".join(lines).rstrip() + "\n"
    md = nav / "atlas.md"
    manifest_path = nav / "atlas.manifest.json"
    # Check ownership of both outputs before any changes.
    for dest in (md, manifest_path):
        if dest.is_symlink() or (dest.exists() and not (dest.read_text(encoding="utf-8").startswith(MARKER) if dest == md else json.loads(dest.read_text(encoding="utf-8")).get("generator") == "cognicode-diagrams-atlas")):
            raise AtlasError(f"archivo preexistente ajeno a esta skill: {dest}")
    manifest = {"generator": "cognicode-diagrams-atlas", "schema_version": 1, "repository": info["repository"],
                "workspace": str(workspace), "artifacts": metadata,
                "knowledge_inputs": knowledge_hashes,
                "markdown_sha256": hashlib.sha256(result.encode("utf-8")).hexdigest(),
                "viewer_links": links, "semantic_certification": "not_claimed"}
    _write_owned(md, result, MARKER)
    _manifest_write(manifest_path, manifest)
    return {"status": "ATLAS_SOURCE_READY", "markdown": str(md), "manifest": str(manifest_path),
            "lenses": list(catalog), "artifacts": sum(len(x["sources"]) + len(x["renders"]) for x in catalog.values()),
            "viewer_links": sum(map(len, links.values())),
            "claims": claim_count, "linked_views": view_count}


def check(repo: Path, *, home: Path | None = None) -> dict:
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise AtlasError("workspace no preparado")
    workspace = Path(info["workspace"])
    nav = workspace / "navigation"
    manifest = nav / "atlas.manifest.json"
    source = nav / "atlas.md"
    for p in (manifest, source):
        if not p.is_file() or not _inside(p, workspace):
            return {"status": "ABSENT", "reason": str(p)}
    data = json.loads(manifest.read_text(encoding="utf-8"))
    if data.get("generator") != "cognicode-diagrams-atlas":
        raise AtlasError("manifiesto no gestionado")
    if data.get("repository") != info["repository"] or data.get("workspace") != str(workspace):
        raise AtlasError("identidad del atlas incompatible con el workspace")
    expected = data.get("artifacts")
    if not isinstance(expected, dict):
        raise AtlasError("manifiesto sin inventario")
    observed = assets(workspace)
    current = {lens: {str(p.relative_to(workspace)): _hash(p)
                      for p in entries["sources"] + entries["renders"]}
               for lens, entries in observed.items()}
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    current_status = ("CURRENT" if expected == current and
                      data.get("knowledge_inputs", {}) == knowledge_fingerprints(workspace) and
                      digest == data.get("markdown_sha256") else "STALE")
    return {"status": current_status, "markdown": str(source), "manifest": str(manifest),
            "note": "CURRENT significa actualizado con los artefactos locales; no prueba semántica"}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("build", "sync", "check"))
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--engine", choices=("podman", "docker"))
    parser.add_argument("--viewers", action="store_true", help="Inspecciona visores propios con HTTP en localhost; sin arranque")
    parser.add_argument("--no-images", action="store_true", help="Solo enlaces, sin miniaturas embebidas")
    args = parser.parse_args(argv)
    try:
        result = check(args.repo) if args.action == "check" else build(
            args.repo, inspect_viewers=args.viewers, engine=args.engine, embed_images=not args.no_images)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (AtlasError, KnowledgeError, WorkspaceError, OSError, ValueError) as exc:
        print(json.dumps({"status": "BLOCKED", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
