#!/usr/bin/env python3
"""Contextual moldable navigation: evidence -> report -> diagram -> question.

Operates exclusively on derived artifacts in ~/.cognicode-diagrams, never on
target source code. No Git, grep, raw files, network, or independent analysis.
"""
from __future__ import annotations

import argparse
import hashlib
from html import escape
import json
import os
from pathlib import Path
from urllib.parse import quote
import sys
import tempfile

import editorial
import report_thinking as report
from workspace import inspect as inspect_workspace

GENERATOR = "cognicode-diagrams-moldable-v1"
MARKER = "<!-- Generated by cognicode-diagrams moldable_views.py v1. -->"
MAX_VIEWS = 70
MAX_BYTES = 2 * 1024 * 1024


class MoldableError(ValueError):
    pass


def key(symbol: str, context: str | None) -> str:
    return hashlib.sha256((symbol + "\0" + (context or "")).encode("utf-8")).hexdigest()[:20]


def paths(root: Path, symbol: str, context: str | None) -> tuple[Path, Path]:
    folder = report.safe(root / "navigation" / "moldable", root)
    name = "symbol-" + key(symbol, context)
    return (report.safe(folder / (name + ".moldable.json"), root),
            report.safe(folder / (name + ".moldable.html"), root))


def _href(target: Path, document: Path, root: Path) -> str:
    report.safe(target, root)
    return quote(os.path.relpath(target, document.parent).replace(os.sep, "/"), safe="/.-_~")


def _existing_report(root: Path, data: dict) -> tuple[Path, Path] | None:
    jp, md = report.paths(root, data)
    for p in (jp, md):
        report.safe(p, root)
        if not p.is_file() or p.stat().st_size > MAX_BYTES:
            return None
    if md.read_text(encoding="utf-8").startswith(report.MARKER) and json.loads(
        jp.read_text(encoding="utf-8")
    ) == data:
        return jp, md
    return None


def _existing_editorial(root: Path, view_id: str, manifest: dict) -> Path | None:
    rel = "lenses/c4/renders/" + view_id + ".editorial.html"
    if rel not in manifest.get("assets", []):
        return None
    p = report.safe(root / rel, root)
    if not p.is_file() or p.stat().st_size > MAX_BYTES:
        return None
    html = p.read_text(encoding="utf-8")
    if not html.startswith(editorial.MARKER) or 'http-equiv="Content-Security-Policy"' not in html:
        raise MoldableError("unsafe editorial HTML in derived workspace")
    return p


def project(root: Path, symbol: str, context: str | None = None) -> dict:
    """Discover ONLY existing, corroborated artifacts for a symbol."""
    symbol = report.text(symbol, "symbol_id")
    if context is not None:
        report.slug(context, "context")
    base = report.project(root, "symbol-passport", symbol=symbol, context=context)
    vocabulary = report.vocab(root)
    language = base["language"]
    selected_terms = sorted(
        [t for t in vocabulary.values() if symbol in t["symbol_ids"]
         and (context is None or t["context_id"] == context)],
        key=lambda t: (t["context_id"], t["term_id"])
    )
    report_links = []
    passport = _existing_report(root, base)
    if passport:
        report_links.append({
            "rel": "open-passport", "kind": "symbol-passport",
            "label": "Comprender este símbolo", "json": str(passport[0].relative_to(root)),
            "markdown": str(passport[1].relative_to(root)),
            "claim_ids": base["evidence"]["claim_ids"]
        })
    for term in selected_terms[:30]:
        card = report.project(root, "term-card", context=term["context_id"], term=term["term_id"])
        pair = _existing_report(root, card)
        if pair:
            report_links.append({
                "rel": "open-term-card", "kind": "term-card",
                "label": term["label"], "context_id": term["context_id"],
                "term_id": term["term_id"], "status": term["status"],
                "json": str(pair[0].relative_to(root)),
                "markdown": str(pair[1].relative_to(root)),
                "claim_ids": card["evidence"]["claim_ids"]
            })
    views = []
    lens = report.safe(root / "lenses" / "c4" / "reports", root)
    if lens.is_dir():
        manifests = sorted(lens.glob("*.atlas.json"))
        if len(manifests) > MAX_VIEWS:
            raise MoldableError("too many C4 views: narrow the scope")
        entity_ids = {c["claim_id"] for c in base["evidence"]["entities"]}
        for p in manifests:
            report.safe(p, root)
            v = report.load(p, root)
            if not isinstance(v, dict) or not isinstance(v.get("claim_ids"), list):
                raise MoldableError("invalid C4 view manifest")
            # This is a symbol-identity match, not a text or filename search.
            if not entity_ids.intersection(v["claim_ids"]):
                continue
            view_id = p.name.removesuffix(".atlas.json")
            try:
                title, nodes, _, coverage = editorial.model(root, view_id)
            except editorial.EditorialError as exc:
                views.append({"view": view_id, "status": "invalid", "reason": str(exc)})
                continue
            if symbol not in {n["symbol"] for n in nodes}:
                continue
            html = _existing_editorial(root, view_id, v)
            views.append({
                "view": view_id, "label": title, "status": "ready" if html else "not-rendered",
                "coverage": coverage,
                "html": str(html.relative_to(root)) if html else None,
                "claim_ids": sorted(v["claim_ids"])
            })

    return {
        "generator": GENERATOR, "schema_version": 1,
        "target": {"kind": "symbol", "symbol_id": symbol, "context_id": context},
        "language": language,
        "evidence": {"claim_ids": base["evidence"]["claim_ids"],
                     "query_ids": base["evidence"]["query_ids"],
                     "coverage": base["evidence"]["coverage"],
                     "basis": base["evidence"]["basis"],
                     "origin": "cognicode"},
        "reports": report_links, "views": views,
        "next": ([{"rel": "render-report", "kind": "symbol-passport"}
                  ] if not passport else []) + [
            {"rel": "render-editorial", "view": v["view"], "focus": symbol}
            for v in views if v["status"] == "not-rendered"
        ],
        "certification": "derived-navigation-only",
    }


def html_page(data: dict, dest: Path, root: Path) -> str:
    esc = lambda value: escape(str(value), quote=True)
    lang = data["language"]
    symbol = data["target"]["symbol_id"]
    candidates = lang.get("alternative_contexts", [])
    def link(rel: str, label: str, target: Path) -> str:
        return '<li><a rel="noopener" href="' + esc(_href(target, dest, root)) + '">' + esc(label) + '</a> <small>(' + esc(rel) + ')</small></li>'
    blocks = []
    for item in data["reports"]:
        blocks.append(link(item["rel"], item["label"] + " · lectura sencilla",
                           root / item["markdown"]))
        blocks.append(link(item["rel"], item["label"] + " · JSON para agentes",
                           root / item["json"]))
    for view in data["views"]:
        if view["html"]:
            blocks.append(link("open-diagram", view["label"] + " · diagrama C4",
                               root / view["html"]))
    if not blocks:
        blocks = ["<li>Aún no existen proyecciones disponibles para esta pregunta.</li>"]
    term_status = " · " + lang["status"] if lang["status"] != "unmapped" else ""
    alternatives = "".join("<li>" + esc(x["context_id"]) + " · " + esc(x["label"]) +
                           " (" + esc(x["status"]) + ")</li>" for x in candidates)
    pending = "".join("<li>" + esc(x["rel"]) + (" · " + esc(x.get("view")) if x.get("view") else "") +
                      " (acción pendiente, NO ejecutada)</li>" for x in data["next"])
    return f'''{MARKER}
<!doctype html><html lang="es"><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(lang["label"])} — conocimiento moldable</title>
<style>body{{margin:0;background:#faf9f6;color:#202b39;font:16px/1.55 system-ui,sans-serif}}
main{{max-width:780px;margin:auto;padding:26px}}
section{{border:1px solid #b0bac6;background:#fff;border-radius:10px;padding:18px;margin:18px 0}}
a{{color:#164ea4}}li{{margin:9px 0;overflow-wrap:anywhere}}
code{{overflow-wrap:anywhere}}small{{color:#46566a}}h1{{line-height:1.2}}</style>
</head><body><main><header><small>CogniCode · misma evidencia, varias perspectivas</small>
<h1>{esc(lang["label"])}{esc(term_status)}</h1>
<p>Identidad técnica: <code>{esc(symbol)}</code></p>
<p>Contexto: {esc(lang["context_id"] or "no identificado")}</p>
<p>{esc(lang.get("definition") or "No hay definición de dominio aceptada. No deducir responsabilidades por el nombre.")}</p>
<p><small>Definición: {esc(lang["definition_authority"])}. Una propuesta no equivale a código probado.</small></p>
</header><section><h2>Elegir perspectiva</h2><ul>{"".join(blocks)}</ul></section>
<section><h2>Cómo lo sabemos</h2>
<p>Claims: {esc(", ".join(data["evidence"]["claim_ids"]))}</p>
<p>Consultas CogniCode: {esc(", ".join(data["evidence"]["query_ids"]))}</p>
<p>Cobertura: {esc(data["evidence"]["coverage"])} · versión: {esc(data["evidence"]["basis"]["status"])}</p>
{link("inspect-evidence", "Ver claims derivados", root / "evidence/claims.json")}
{link("inspect-evidence", "Ver consultas derivadas", root / "evidence/queries.json")}
<p><small>Las rutas a evidencia nunca autorizan leer el checkout original.</small></p></section>
{"<section><h2>El término varía por contexto</h2><ul>" + alternatives + "</ul></section>" if alternatives else ""}
{"<section><h2>Próximas consultas útiles</h2><ul>" + pending + "</ul></section>" if pending else ""}
<p><small>Solo proyección de hechos registrados; ni el informe ni el diagrama prueban comportamiento runtime ni vigencia del código.</small></p>
</main></body></html>'''


def owned_write(dest: Path, value: str, root: Path, *, json_file: bool = False):
    report.safe(dest, root)
    if dest.exists():
        if not dest.is_file() or dest.stat().st_size > MAX_BYTES:
            raise MoldableError("invalid moldable output")
        old = dest.read_text(encoding="utf-8")
        try:
            valid = (json.loads(old).get("generator") == GENERATOR if json_file
                     else old.startswith(MARKER))
        except (ValueError, AttributeError, UnicodeError):
            valid = False
        if not valid:
            raise MoldableError("unowned moldable output")
        if old == value:
            return
    fd, name = tempfile.mkstemp(prefix=".moldable-", suffix=".tmp", dir=dest.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(value)
        os.chmod(name, 0o644)
        os.replace(name, dest)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def build(repo: Path, symbol: str, *, context: str | None = None,
          home: Path | None = None, check: bool = False) -> dict:
    info = inspect_workspace(repo, home=home)
    if info["status"] != "ready":
        raise MoldableError("derived workspace not ready")
    root = Path(info["workspace"])
    data = project(root, symbol, context)
    jpath, hpath = paths(root, symbol, context)
    # Preflight does not write. Both outputs are validated before any changes.
    rendered = html_page(data, hpath, root)
    if check:
        return {"status": "NAVIGATION_READY_TO_RENDER", "views": len(data["views"]),
                "reports": len(data["reports"]), "pending": data["next"],
                "note": "Only derived evidence was inspected; no checkout read."}
    folder = report.safe(jpath.parent, root)
    if folder.exists() and not folder.is_dir():
        raise MoldableError("moldable directory is not a folder")
    folder.mkdir(parents=True, exist_ok=True)
    for p, is_json in ((jpath, True), (hpath, False)):
        if p.exists():
            old = p.read_text(encoding="utf-8")
            try:
                valid = (json.loads(old).get("generator") == GENERATOR if is_json
                         else old.startswith(MARKER))
            except (ValueError, AttributeError, UnicodeError):
                valid = False
            if not valid:
                raise MoldableError("unowned moldable output: " + p.name)
    raw = json.dumps(data, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    owned_write(jpath, raw, root, json_file=True)
    owned_write(hpath, rendered, root)
    return {"status": "MOLDABLE_RENDERED", "json": str(jpath), "html": str(hpath),
            "views": len(data["views"]), "reports": len(data["reports"]),
            "note": "Sync atlas; no claims of source freshness."}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--symbol", required=True)
    parser.add_argument("--context")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        outcome = build(args.repo, args.symbol, context=args.context, check=args.check)
        print(json.dumps(outcome, ensure_ascii=False, indent=2))
        return 0
    except (MoldableError, report.ReportError, editorial.EditorialError, OSError, ValueError) as exc:
        print(json.dumps({"status": "BLOCKED", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
